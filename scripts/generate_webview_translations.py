def main():
    # 加载现有字典
    dict_path = DATA_DIR / 'webview-translations.json'
    with open(dict_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    # 统计
    existing_keys = {k for k in data if not k.startswith('_') and not k.startswith('===')}
    new_count = 0
    updated_count = 0

    # 合并新翻译（在 _meta 之后、第一个 === 之前插入）
    # 找到第一个 === 注释键的位置
    keys = list(data.keys())
    insert_pos = 0
    for i, k in enumerate(keys):
        if k.startswith('==='):
            insert_pos = i
            break

    # 构建新的有序字典
    new_data = OrderedDict()
    # 保留 _meta 和第一个 === 之前的内容
    for i, k in enumerate(keys):
        if i < insert_pos:
            new_data[k] = data[k]

    # 添加新翻译（在第一个 === 之前）
    section_added = False
    for en, zh in NEW_TRANSLATIONS.items():
        if en in existing_keys:
            # 已存在，检查是否需要更新
            if data[en] != zh:
                updated_count += 1
            continue
        if not section_added:
            new_data["=== 新增 Webview UI 翻译 ==="] = ""
            section_added = True
        new_data[en] = zh
        new_count += 1

    # 保留剩余内容
    for i, k in enumerate(keys):
        if i >= insert_pos:
            new_data[k] = data[k]

    # 写回
    with open(dict_path, 'w', encoding='utf-8') as f:
        json.dump(new_data, f, ensure_ascii=False, indent='    ')

    print(f"新增翻译: {new_count} 条")
    print(f"已存在（跳过）: {len(NEW_TRANSLATIONS) - new_count} 条")
    print(f"总字典条目: {len([k for k in new_data if not k.startswith('_') and not k.startswith('===')])}")

if __name__ == '__main__':
    main()
